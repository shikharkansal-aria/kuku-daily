"""Bundle real pipeline outputs on the fictional demo show into web/data.js for the static prototype.

Usage: python -m tools.export_web
Inputs are all public-safe: data/sample_show (fictional), data/catalog.json (public metadata), data/demo_cache.
No LLM calls; re-run after a new demo-show run to refresh the page.
"""
import json
from pathlib import Path

from tools.drops import load_show
from tools.gates import GRACE_H, LEVELS, TIERS
from tools.persona import QUESTIONS

ROOT = Path(__file__).resolve().parent.parent
CACHE = ROOT / "data" / "demo_cache"

# Kuku-pack aggregates, as stated in submission/solution.md (from validation_report.md of the final Groq run)
RESULTS = {
    "episodes": 50, "drops": 21, "drops_in_range": 19, "strong_cliffhangers": 9, "teasers_grounded": 21,
    "teasers_repaired": 5, "spearman": 0.73, "within_one_point": 47, "shared_cuts": 10,
    "cents_per_show": 2, "usd_per_million_viewers": 800, "reviews": 1100, "price_share_pct": 20,
    "too_many_shows_pct": 1, "first_screen_shows": "25 to 30",
}


def load(name):
    return json.loads((CACHE / name).read_text(encoding="utf-8"))


def build():
    show = load("show_entry.json") | {"title": "The Lost Haveli", "platform": "Demo show (fictional)"}
    eps = [{"ep": e["ep"], "seconds": e["seconds"], "logline": e["logline"],
            "tail": [{k: b[k] for k in ("type", "speaker", "cue", "start", "end", "text")} for b in e["tail"]]}
           for e in load_show(ROOT / "data" / "sample_show")]
    drops = {lang: {k: d[k] for k in ("episode_scores", "drops")} for lang in ("english", "hinglish")
             for d in [load(f"drops_{lang}.json")]}
    viewers = {v["input"]["language"]: v for v in (load(f"viewers/{n}.json") for n in ("p01", "p05"))}
    for v in viewers.values():  # the run labelled the demo show as the input pack; the public page calls it what it is
        v["match"]["picks"] = [p | {k: show[k] for k in ("title", "platform")} if p["id"] == show["id"] else p
                               for p in v["match"]["picks"]]
    catalog = json.loads((ROOT / "data" / "catalog.json").read_text(encoding="utf-8"))
    return {"show": show, "episodes": eps, "drops": drops, "viewers": viewers, "catalog": catalog,
            "questions": QUESTIONS, "gates": {"tiers": TIERS, "levels": LEVELS, "grace_h": GRACE_H},
            "results": RESULTS}


def main():
    data = build()
    assert set(data["viewers"]) == {"english", "hinglish"}, "need one viewer per language"
    assert all(d["grounded"] for lang in data["drops"].values() for d in lang["drops"]), "ungrounded teaser"
    out = ROOT / "web" / "data.js"
    out.write_text("// generated by tools/export_web.py; do not edit by hand\nwindow.KD = "
                   + json.dumps(data, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    print(out, out.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
